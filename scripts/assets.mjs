import { mkdir, readFile, writeFile } from "node:fs/promises";
import { existsSync, createWriteStream } from "node:fs";
import { dirname, join, extname } from "node:path";
import { pipeline } from "node:stream/promises";
import { spawn } from "node:child_process";

const root = process.cwd();
const assetDir = join(root, "public", "assets");
const modelDir = join(root, "public", "models");
const blenderDir = join(root, "scripts", "blender");
const api = "https://api.polyhaven.com";

const preferred = {
  hdri: ["moonlit_golf", "rogland_clear_night", "winter_evening", "kloppenheim_06_puresky", "wasteland_clouds"],
  concrete: ["concrete_leaking_001", "concrete_floor_001", "concrete_001"],
  metal: ["metal_plate_001", "painted_metal_001", "metal_001"],
  steel: ["brushed_steel", "brushed_metal_001", "metal_rough_001"],
  snow: ["snow_001", "snow", "ice_001"],
  asphalt: ["asphalt_road", "asphalt_001", "road"],
};

async function getJson(path) {
  const response = await fetch(`${api}${path}`);
  if (!response.ok) throw new Error(`Poly Haven ${path}: ${response.status}`);
  return response.json();
}

function findAssetId(catalog, candidates, keywords) {
  for (const candidate of candidates) if (catalog[candidate]) return candidate;
  const entries = Object.entries(catalog);
  const found = entries.find(([id, meta]) => {
    const haystack = `${id} ${meta?.name ?? ""}`.toLowerCase();
    return keywords.some((keyword) => haystack.includes(keyword));
  });
  return found?.[0];
}

function collectFiles(value, path = []) {
  const matches = [];
  if (!value || typeof value !== "object") return matches;
  for (const [key, child] of Object.entries(value)) {
    const nextPath = [...path, key];
    if (typeof child === "string" && /^https?:\/\//.test(child)) matches.push({ path: nextPath, url: child });
    else matches.push(...collectFiles(child, nextPath));
  }
  return matches;
}

function chooseFile(files, type) {
  const allowed = type === "hdri" ? [".hdr", ".exr"] : [".jpg", ".jpeg", ".png"];
  const candidates = files.filter(({ url }) => allowed.includes(extname(new URL(url).pathname).toLowerCase()));
  const score = ({ path, url }) => {
    const text = `${path.join("/")} ${url}`.toLowerCase();
    let result = 0;
    if (text.includes(type === "hdri" ? "2k" : "2k")) result += 20;
    if (text.includes(type === "hdri" ? "hdri" : "diff")) result += 15;
    if (text.includes("jpg")) result += 3;
    if (text.includes("1k")) result -= 2;
    return result;
  };
  return [...candidates].sort((a, b) => score(b) - score(a))[0];
}

async function download(url, target) {
  await mkdir(dirname(target), { recursive: true });
  const response = await fetch(url);
  if (!response.ok) throw new Error(`Download ${url}: ${response.status}`);
  await pipeline(response.body, createWriteStream(target));
}

async function main() {
  await Promise.all([mkdir(assetDir, { recursive: true }), mkdir(modelDir, { recursive: true }), mkdir(blenderDir, { recursive: true })]);
  const catalog = await getJson("/assets");
  const selections = {
    hdri: findAssetId(catalog, preferred.hdri, ["night", "moon", "evening", "dark"]),
    concrete: findAssetId(catalog, preferred.concrete, ["concrete"]),
    metal: findAssetId(catalog, preferred.metal, ["painted", "metal"]),
    steel: findAssetId(catalog, preferred.steel, ["brushed", "steel"]),
    snow: findAssetId(catalog, preferred.snow, ["snow", "ice"]),
    asphalt: findAssetId(catalog, preferred.asphalt, ["asphalt", "road"]),
  };
  const missing = Object.entries(selections).filter(([, id]) => !id);
  if (missing.length) throw new Error(`Could not find Poly Haven assets for: ${missing.map(([kind]) => kind).join(", ")}`);

  const manifest = [];
  for (const [kind, id] of Object.entries(selections)) {
    const [info, files] = await Promise.all([getJson(`/info/${id}`), getJson(`/files/${id}`)]);
    const selected = chooseFile(collectFiles(files), kind);
    if (!selected) throw new Error(`No supported file found for ${kind} / ${id}`);
    const extension = extname(new URL(selected.url).pathname).toLowerCase();
    const filename = `${kind}-${id}${extension}`;
    const target = join(assetDir, filename);
    if (!existsSync(target)) await download(selected.url, target);
    manifest.push({ kind, id, name: info.name ?? id, source: `${api}/asset/${id}`, url: selected.url, file: `public/assets/${filename}`, license: "CC0" });
    console.log(`${kind}: ${id} -> ${filename}`);
  }

  const credits = [
    "# Asset credits",
    "",
    "Generated by `npm run assets`. All downloaded Poly Haven assets are CC0.",
    "",
    "| Purpose | Asset | Local file | Source | License |",
    "| --- | --- | --- | --- | --- |",
    ...manifest.map((item) => `| ${item.kind} | ${item.name} (${item.id}) | ${item.file} | [Poly Haven](${item.source}) | ${item.license} |`),
    "",
  ];
  await writeFile(join(root, "CREDITS.md"), `${credits.join("\\n")}\\n`);

  const blender = process.env.BLENDER_BIN || "blender";
  await new Promise((resolve, reject) => {
    const child = spawn(blender, ["-b", "--python", join(blenderDir, "build_assets.py"), "--", "--output", modelDir, "--assets", assetDir], { stdio: "inherit" });
    child.on("error", reject);
    child.on("exit", (code) => code === 0 ? resolve() : reject(new Error(`Blender exited with ${code}`)));
  });
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : error);
  process.exitCode = 1;
});
